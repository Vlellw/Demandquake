import { Sparkles, Globe2 } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import { Tooltip, TooltipContent, TooltipTrigger } from "@/components/ui/tooltip";

export function ObservedTag({ label = "Observed", count }: { label?: string; count?: number }) {
  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <span>
          <Badge variant="observed">
            <Globe2 />
            {label}
            {typeof count === "number" ? ` · ${count}` : ""}
          </Badge>
        </span>
      </TooltipTrigger>
      <TooltipContent className="max-w-60">Retrieved from the live web by Context.dev and linked to its original source.</TooltipContent>
    </Tooltip>
  );
}

export function InferredTag({ label = "AI hypothesis" }: { label?: string }) {
  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <span>
          <Badge variant="inferred">
            <Sparkles />
            {label}
          </Badge>
        </span>
      </TooltipTrigger>
      <TooltipContent className="max-w-60">Generated by AI from the evidence. Treat it as an assumption to validate, not a fact.</TooltipContent>
    </Tooltip>
  );
}
